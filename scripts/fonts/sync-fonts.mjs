// Copies the self-hosted web fonts from the pinned @fontsource packages (SIL OFL 1.1) into
// apps/web/src/theme/fonts and writes the @font-face CSS next to them. Run after changing the
// plan below: `node scripts/fonts/sync-fonts.mjs`. Output is committed; nothing is fetched at run time.
// Only the latin and latin-ext subsets are shipped (unicode-range keeps latin-ext unfetched until
// a page needs it). Eager faces load with the app; lazy ones load when the editor font is used.
import { copyFileSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..', '..');
const webDir = join(root, 'apps', 'web');
const outDir = join(webDir, 'src', 'theme', 'fonts');
const require = createRequire(join(webDir, 'package.json'));
const SUBSETS = ['latin', 'latin-ext'];

/** css: output file name. The names are the Google Fonts family names the app uses. */
export const PLAN = [
  { css: 'core', slug: 'figtree', family: 'Figtree', faces: [[400, 500, 600, 700], ['normal']] },
  { css: 'core', slug: 'poppins', family: 'Poppins', faces: [[500, 600], ['normal']] },
  { css: 'core', slug: 'roboto', family: 'Roboto', faces: [[500], ['normal']] },
  {
    css: 'poppins',
    slug: 'poppins',
    family: 'Poppins',
    faces: [
      [400, 700],
      ['normal', 'italic'],
    ],
  },
  {
    css: 'lora',
    slug: 'lora',
    family: 'Lora',
    faces: [
      [400, 700],
      ['normal', 'italic'],
    ],
  },
  {
    css: 'nunito',
    slug: 'nunito',
    family: 'Nunito',
    faces: [
      [400, 700],
      ['normal', 'italic'],
    ],
  },
  {
    css: 'jetbrains-mono',
    slug: 'jetbrains-mono',
    family: 'JetBrains Mono',
    faces: [
      [400, 700],
      ['normal', 'italic'],
    ],
  },
  { css: 'caveat', slug: 'caveat', family: 'Caveat', faces: [[400, 700], ['normal']] },
];

function unicodeRange(pkgDir, slug, subset, weight, style) {
  const file = join(pkgDir, `${weight}${style === 'italic' ? '-italic' : ''}.css`);
  const css = readFileSync(file, 'utf8');
  const block = css
    .split('@font-face')
    .find((b) => b.includes(`${slug}-${subset}-${weight}-${style}.woff2`));
  const range = block && /unicode-range:\s*([^;]+);/.exec(block)?.[1];
  if (!range) throw new Error(`no unicode-range for ${slug} ${subset} ${weight} ${style}`);
  return range.replace(/,/g, ', ');
}

mkdirSync(outDir, { recursive: true });
const sheets = new Map();
const header = (name) =>
  `/*\n * Self-hosted ${name} fonts, generated by scripts/fonts/sync-fonts.mjs from @fontsource (SIL OFL 1.1;\n * docs/PROVENANCE.md). Do not edit by hand.\n */\n`;
for (const entry of PLAN) {
  const pkgDir = dirname(require.resolve(`@fontsource/${entry.slug}/package.json`));
  const [weights, styles] = entry.faces;
  for (const weight of weights) {
    for (const style of styles) {
      for (const subset of SUBSETS) {
        const name = `${entry.slug}-${subset}-${weight}-${style}.woff2`;
        copyFileSync(join(pkgDir, 'files', name), join(outDir, name));
        const range = unicodeRange(pkgDir, entry.slug, subset, weight, style);
        const block =
          `@font-face {\n  font-family: ${entry.family.includes(' ') ? `'${entry.family}'` : entry.family};\n  font-style: ${style};\n  font-weight: ${weight};\n` +
          `  font-display: swap;\n  src: url('./${name}') format('woff2');\n  unicode-range: ${range};\n}\n`;
        sheets.set(entry.css, `${sheets.get(entry.css) ?? header(entry.css)}\n${block}`);
      }
    }
  }
}

// The OFL asks for the copyright line and licence text to travel with the fonts: ship them as
// /fonts/OFL-LICENSES.txt next to the emoji font.
const licences = [...new Set(PLAN.map((e) => e.slug))].map((slug) => {
  const pkgDir = dirname(require.resolve(`@fontsource/${slug}/package.json`));
  return `==== ${slug} (@fontsource/${slug}) ====\n\n${readFileSync(join(pkgDir, 'LICENSE'), 'utf8').trim()}\n`;
});
writeFileSync(
  join(webDir, 'public', 'fonts', 'OFL-LICENSES.txt'),
  `Fonts bundled with Atrium under the SIL Open Font License 1.1 (generated by scripts/fonts/sync-fonts.mjs).\n\n${licences.join('\n')}`,
);
for (const [name, css] of sheets) writeFileSync(join(outDir, `${name}.css`), css);
console.log(`wrote ${sheets.size} stylesheets to ${outDir}`);
